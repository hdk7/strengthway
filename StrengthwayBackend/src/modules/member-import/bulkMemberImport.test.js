"use strict";

jest.setTimeout(30000);

const request = require("supertest");
const jwt = require("jsonwebtoken");
const XLSX = require("xlsx");
const { connectDB, disconnectDB } = require("../../config/database");
const app = require("../../app");
const { JWT_SECRET } = require("../../config/env");

const Member = require("../members/member.model");
const User = require("../auth/user.model");
const memberImportService = require("./memberImport.service");

describe("Bulk Member Import Feature Integration Suite", () => {
  const ts = Date.now().toString().slice(-4);
  let adminToken;
  let adminUserId;
  let nonAdminToken;
  let nonAdminUserId;

  const existingMemberId = `MEM-EXIST-${ts}`;
  const existingEmail = `existing.${ts}@strengthway.com`;
  const existingMobile = `91${ts}000001`;

  const createdMemberIds = [];

  beforeAll(async () => {
    await connectDB();

    // 1. Create Admin User
    const adminUser = await User.create({
      name: "Import Admin",
      email: `admin.import.${ts}@strengthway.com`,
      passwordHash: "dummyhash",
      role: "admin",
      isActive: true,
    });
    adminUserId = adminUser._id;
    adminToken = jwt.sign(
      {
        id: adminUser._id.toString(),
        role: "admin",
        name: adminUser.name,
        email: adminUser.email,
      },
      JWT_SECRET,
      { expiresIn: "1h" }
    );

    // 2. Create Non-Admin (Member) User
    const regularUser = await User.create({
      name: "Regular Member",
      email: `regular.member.${ts}@strengthway.com`,
      passwordHash: "dummyhash",
      role: "member",
      isActive: true,
    });
    nonAdminUserId = regularUser._id;
    nonAdminToken = jwt.sign(
      {
        id: regularUser._id.toString(),
        role: "member",
        name: regularUser.name,
        email: regularUser.email,
      },
      JWT_SECRET,
      { expiresIn: "1h" }
    );

    // 3. Create Existing Member in DB for duplicate testing
    const existingMember = await Member.create({
      id: existingMemberId,
      fullName: "Existing Gym Member",
      firstName: "Existing",
      lastName: "Gym Member",
      email: existingEmail,
      mobile: existingMobile,
      gender: "Male",
      dob: "1994-06-15",
      address: "123 Old Gym Lane",
      city: "Mumbai",
      state: "Maharashtra",
      pincode: "400001",
      emergencyName: "Contact Parent",
      status: "Active",
      isDeleted: false,
    });
    createdMemberIds.push(existingMember.id);
  });

  afterAll(async () => {
    // Clean up created records
    if (createdMemberIds.length > 0) {
      await Member.deleteMany({ id: { $in: createdMemberIds } });
    }
    await User.deleteMany({ _id: { $in: [adminUserId, nonAdminUserId] } });
    await disconnectDB();
  });

  describe("1. Access Control & Authorization", () => {
    it("should reject unauthenticated request with 401", async () => {
      const res = await request(app)
        .post("/api/v1/members/import/execute")
        .send({ records: [] });
      expect([401, 403]).toContain(res.status);
    });

    it("should reject non-admin users with 403", async () => {
      const res = await request(app)
        .post("/api/v1/members/import/execute")
        .set("Authorization", `Bearer ${nonAdminToken}`)
        .send({ records: [] });
      expect(res.status).toBe(403);
    });
  });

  describe("2. Excel Template Generation", () => {
    it("should download formatted .xlsx template with 200 OK", async () => {
      const res = await request(app)
        .get("/api/v1/members/import/template?format=xlsx")
        .set("Authorization", `Bearer ${adminToken}`);

      expect(res.status).toBe(200);
      expect(res.headers["content-type"]).toContain("spreadsheetml.sheet");
      expect(res.headers["content-disposition"]).toContain(
        "StrengthWay_Member_Import_Template.xlsx"
      );

      // Verify template structure generated by service
      const template = memberImportService.generateTemplate("xlsx");
      expect(template.buffer).toBeInstanceOf(Buffer);
      const workbook = XLSX.read(template.buffer, { type: "buffer" });
      expect(workbook.SheetNames).toContain("Member Import Template");
      expect(workbook.SheetNames).toContain("Instructions & Rules");
    });
  });

  describe("3. Validation & Two-Tier Duplicate Detection", () => {
    it("should correctly identify valid, file-duplicate, db-duplicate, and invalid rows", async () => {
      const testRows = [
        // Row 1: Valid unique member
        {
          rowNumber: 2,
          fullName: `Valid Member One ${ts}`,
          email: `valid.one.${ts}@example.com`,
          mobile: `98${ts}00001`,
          gender: "Male",
          dob: "1997-04-12",
          address: "45 Ocean View Road",
          city: "Mumbai",
          state: "Maharashtra",
          pincode: "400050",
          emergencyName: "Anita Sharma",
        },
        // Row 2: Invalid row (bad email, age < 18, missing city)
        {
          rowNumber: 3,
          fullName: "Minor Kid",
          email: "not-an-email",
          mobile: "123",
          gender: "Male",
          dob: "2015-01-01", // Under 18
          address: "Short",
          city: "",
          state: "MH",
          pincode: "99",
          emergencyName: "",
        },
        // Row 3: Within-file duplicate of Row 1 (same email)
        {
          rowNumber: 4,
          fullName: "Duplicate Inside File",
          email: `valid.one.${ts}@example.com`, // Matches Row 1
          mobile: `98${ts}00002`,
          gender: "Female",
          dob: "1995-08-20",
          address: "99 Hill Road",
          city: "Pune",
          state: "Maharashtra",
          pincode: "411001",
          emergencyName: "Sameer Verma",
        },
        // Row 4: Database duplicate (matches existing member in DB)
        {
          rowNumber: 5,
          fullName: "Existing Member In DB",
          email: existingEmail, // Already in DB
          mobile: `98${ts}00003`,
          gender: "Male",
          dob: "1990-01-01",
          address: "100 New Road",
          city: "Delhi",
          state: "Delhi",
          pincode: "110001",
          emergencyName: "Parent Name",
        },
      ];

      const res = await request(app)
        .post("/api/v1/members/import/validate")
        .set("Authorization", `Bearer ${adminToken}`)
        .send({ rows: testRows });

      expect(res.status).toBe(200);
      const data = res.body.data;
      expect(data).toHaveProperty("summary");
      expect(data.summary.totalRows).toBe(4);
      expect(data.summary.readyCount).toBe(1);
      expect(data.summary.invalidCount).toBe(1);
      expect(data.summary.fileDuplicateCount).toBe(1);
      expect(data.summary.dbDuplicateCount).toBe(1);

      // Verify specific statuses
      expect(data.rows[0].status).toBe("READY");
      expect(data.rows[1].status).toBe("INVALID");
      expect(data.rows[2].status).toBe("DUPLICATE_IN_FILE");
      expect(data.rows[3].status).toBe("EXISTING_IN_DB");
    });
  });

  describe("4. Bulk Import Execution", () => {
    it("should successfully import valid member records into MongoDB Atlas", async () => {
      const recordsToImport = [
        {
          rowNumber: 2,
          fullName: `Bulk Imported Athlete A ${ts}`,
          email: `athlete.a.${ts}@strengthway.com`,
          mobile: `98${ts}11111`,
          gender: "Male",
          dob: "1995-10-15",
          address: "Flat 101, Fitness Tower",
          city: "Bengaluru",
          state: "Karnataka",
          pincode: "560001",
          emergencyName: "Kavita Athlete",
          emergencyPhone: `98${ts}11112`,
          bloodGroup: "O+",
          height: 180,
          weight: 78,
          status: "READY",
        },
        {
          rowNumber: 3,
          fullName: `Bulk Imported Athlete B ${ts}`,
          email: `athlete.b.${ts}@strengthway.com`,
          mobile: `98${ts}22222`,
          gender: "Female",
          dob: "1998-03-22",
          address: "Villa 5, Palm Grove",
          city: "Bengaluru",
          state: "Karnataka",
          pincode: "560002",
          emergencyName: "Rohan Athlete",
          bloodGroup: "B+",
          height: 165,
          weight: 58,
          status: "READY",
        },
      ];

      const res = await request(app)
        .post("/api/v1/members/import/execute")
        .set("Authorization", `Bearer ${adminToken}`)
        .send({
          records: recordsToImport,
          sourceFilename: "test_batch_athletes.xlsx",
        });

      expect([200, 201]).toContain(res.status);
      const data = res.body.data;
      expect(data.importedCount).toBe(2);
      expect(data.failedCount).toBe(0);
      expect(data.importedMembers).toHaveLength(2);

      // Verify in MongoDB Atlas
      for (const imported of data.importedMembers) {
        createdMemberIds.push(imported.id);
        const inDb = await Member.findOne({ id: imported.id });
        expect(inDb).not.toBeNull();
        expect(inDb.status).toBe("Active");
        expect(inDb.isDeleted).toBe(false);
        expect(inDb.emergencyName).toBeTruthy();
        expect(inDb.physicalStats).toHaveProperty("bmi");
      }
    });

    it("should safely reject execution when no valid records are provided", async () => {
      const res = await request(app)
        .post("/api/v1/members/import/execute")
        .set("Authorization", `Bearer ${adminToken}`)
        .send({
          records: [
            {
              rowNumber: 2,
              fullName: "Invalid Row Only",
              status: "INVALID",
              errors: ["Missing required fields"],
            },
          ],
        });

      expect(res.status).toBe(400);
    });
  });
});
